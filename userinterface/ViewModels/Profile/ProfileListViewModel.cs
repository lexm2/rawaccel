        private int FindOptimalInsertPosition()
        {
            // Find the first "Profile X" entry (auto-generated name) after the first profile
            for (int i = 1; i < Profiles.Count; i++)
            {
                var profile = Profiles[i];
                if (IsAutoGeneratedProfileName(profile.Name.ModelValue))
                {
                    return i; // Insert before the first auto-generated profile
                }
            }

            return Profiles.Count;
        }

        private static bool IsAutoGeneratedProfileName(string name)
        {
            return System.Text.RegularExpressions.Regex.IsMatch(name, @"^Profile \d+$");
        }

        public bool TryAddProfileAtPosition(int position)
        {
            var profileName = GenerateProfileName();
            if (!profilesModel.TryAddNewDefault()) return false;

            // Move the newly added profile to the specified position
            var newProfile = profilesModel.Elements[^1];
            profilesModel.TryRemoveElement(newProfile);

            // Ensure position is within bounds
            int clampedPosition = Math.Max(1, Math.Min(position, profilesModel.Elements.Count));
            profilesModel.TryInsert(clampedPosition, newProfile);

            // Set the name
            newProfile.Name.TryUpdateModelDirectly(profileName);

            return true;
        }

        private bool TryAddProfileWithName(string profileName)
        {
            if (string.IsNullOrEmpty(profileName)) return false;

            if (!profilesModel.TryAddNewDefault()) return false;

            // Set the name of the newly added profile
            var newProfile = profilesModel.Elements[^1];
            return newProfile.Name.TryUpdateModelDirectly(profileName);
        }

        private string GenerateProfileName()
        {
            for (int i = 1; i <= MaxProfileAttempts; i++)
            {
                string name = $"Profile {i}";
                if (!profilesModel.TryGetElement(name, out _))
                {
                    return name;
                }
            }
            return string.Empty;
        }

        private async Task ProcessOperationQueue()
        {
            if (isProcessingQueue) return;

            isProcessingQueue = true;

            try
            {
                while (pendingOperations.TryDequeue(out var operation))
                {
                    await operationQueue.WaitAsync();
                    try
                    {
                        await operation();
                    }
                    finally
                    {
                        operationQueue.Release();
                    }
                }
            }
            finally
            {
                isProcessingQueue = false;
            }
        }

        private async Task WaitForAnimationsToComplete()
        {
            if (animationStateService != null)
            {
                if (!animationStateService.AreAnimationsActive)
                {
                    return;
                }

                var tcs = new TaskCompletionSource<bool>();

                void OnAnimationStateChanged(object? sender, bool isActive)
                {
                    if (!isActive)
                    {
                        tcs.TrySetResult(true);
                    }
                }

                animationStateService.AnimationStateChanged += OnAnimationStateChanged;

                try
                {
                    if (!animationStateService.AreAnimationsActive)
                    {
                        return;
                    }

                    await tcs.Task;
                }
                finally
                {
                    animationStateService.AnimationStateChanged -= OnAnimationStateChanged;
                }
            }
            else
            {
                await Task.Delay(400);
            }
        }


        public bool RemoveProfile(BE.IProfileModel profile) => profile != null && profilesModel.TryRemoveElement(profile);


        public void Dispose()
        {
            if (disposed)
                return;

            operationQueue?.Dispose();

            disposed = true;
            GC.SuppressFinalize(this);
        }
    }
